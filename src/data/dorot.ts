/** Compact constructor for a patriarchal card. */
function p(
  houseId: string,
  index: number,
  title: string,
  episode: string,
  humanPractice: string,
  question: string,
): DorotCard {
  const figure = houseId.replace("house-", "");
  return { id: `${figure}-${index}`, houseId, index, title, episode, humanPractice, question };
}

/**
 * Constructor for a matriarchal card **brought to the patriarchal shape** —
 * P10-7's work. The old `m()` (episode + coreEnergy, title set equal to the
 * episode) was the stub form the file's header always named first-draft;
 * `coreEnergy` is kept, because it was authored and the Herald and the House
 * plate both render it.
 */
function mw(
  houseId: string,
  index: number,
  title: string,
  episode: string,
  coreEnergy: string,
  humanPractice: string,
  question: string,
): DorotCard {
  const figure = houseId.replace("house-", "");
  return { id: `${figure}-${index}`, houseId, index, title, episode, coreEnergy, humanPractice, question };
}

