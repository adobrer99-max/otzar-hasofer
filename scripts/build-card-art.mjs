#!/usr/bin/env node
/**
 * Register the card art shipped with the site. Scans public/art/letters/ and
 * public/art/dorot/ for images named by their card id (aleph.jpg,
 * abraham-1.webp, …), reads optional alt text and credits from
 * public/art/art.json, and writes src/data/shippedCardArt.generated.ts.
 *
 * Runs before every build (the `prebuild` script), so a deploy picks up
 * whatever images are committed — the designer only adds files. Each URL
 * carries a short content hash, so a replaced image is a new URL and an
 * installed app's image cache never serves the old one. See CARD-ART.md.
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, extname, basename, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const KINDS = { letters: "letter", dorot: "dorot" };
const IMAGE = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);
/** Above this, warn: a card image this heavy slows phones down. */
export const SIZE_WARNING_BYTES = 600 * 1024;

/**
 * Collect the shipped art under `artDir` (pure apart from reading files).
 * Returns the entries plus any problems: `errors` stop the build, `warnings`
 * are printed.
 */
export function collectArt(artDir) {
  const entries = [];
  const errors = [];
  const warnings = [];
  let meta = {};
  const metaPath = join(artDir, "art.json");
  if (existsSync(metaPath)) {
    try {
      meta = JSON.parse(readFileSync(metaPath, "utf8"));
    } catch (err) {
      errors.push(`public/art/art.json isn't valid JSON: ${err.message}`);
    }
  }
  const seen = new Map();
  for (const [folder, kind] of Object.entries(KINDS)) {
    const dir = join(artDir, folder);
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).sort()) {
      const ext = extname(file).toLowerCase();
      if (!IMAGE.has(ext)) continue;
      const name = basename(file, extname(file));
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
        warnings.push(`art/${folder}/${file}: names are lower-case card ids (e.g. aleph.jpg, abraham-1.jpg) — skipped`);
        continue;
      }
      const id = `${kind}:${name}`;
      if (seen.has(id)) {
        errors.push(`${id} has two images: art/${folder}/${seen.get(id)} and art/${folder}/${file} — keep one`);
        continue;
      }
      seen.set(id, file);
      const bytes = readFileSync(join(dir, file));
      if (bytes.length > SIZE_WARNING_BYTES) {
        warnings.push(`art/${folder}/${file} is ${Math.round(bytes.length / 1024)} KB — aim for under ${SIZE_WARNING_BYTES / 1024} KB (see CARD-ART.md)`);
      }
      const hash = createHash("sha1").update(bytes).digest("hex").slice(0, 8);
      const info = meta[id] ?? {};
      entries.push({
        id,
        src: `/art/${folder}/${file}?v=${hash}`,
        ...(typeof info.alt === "string" && info.alt.trim() ? { alt: info.alt.trim() } : {}),
        ...(typeof info.credit === "string" && info.credit.trim() ? { credit: info.credit.trim() } : {}),
      });
    }
  }
  for (const id of Object.keys(meta)) {
    if (!seen.has(id)) warnings.push(`art.json describes ${id}, but no image for it was found`);
  }
  return { entries, errors, warnings };
}

export function renderModule(entries) {
  return `// Generated by scripts/build-card-art.mjs from public/art/ — do not edit.
// Add or replace images there (see CARD-ART.md); every build regenerates this.

export interface ShippedArtEntry {
  id: string;
  src: string;
  alt?: string;
  credit?: string;
}

export const shippedCardArt: ShippedArtEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

function main() {
  const { entries, errors, warnings } = collectArt(join(ROOT, "public", "art"));
  for (const w of warnings) console.warn(`card art: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`card art: ${e}`);
    process.exit(1);
  }
  const out = join(ROOT, "src", "data", "shippedCardArt.generated.ts");
  const next = renderModule(entries);
  // Only touch the file when it changes, so a build leaves no stray diff.
  if (!existsSync(out) || readFileSync(out, "utf8") !== next) writeFileSync(out, next);
  console.log(`card art: ${entries.length} shipped image${entries.length === 1 ? "" : "s"} registered`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
